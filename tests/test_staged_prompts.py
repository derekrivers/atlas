"""ATLAS-103: staged planner prompt templates.

Three per-stage templates (epics / tickets-per-epic / dependencies) are
projections of the §3.11 proposal contract, assembled by ATLAS-104 into
one full-state proposal (planning-large-corpora.md §4/§4.1, ADR-0010).
This ticket builds the template ARTIFACTS only — these tests assert each
renders deterministically through the EXISTING renderer, fails closed on
missing/extra variables, carries the stage's projection instruction and
the environment-owns-identity rule, and that the live single-call path
is structurally protected and unchanged.

The fixture schema is clearly labelled: the real per-stage projection
schema is caller-supplied (ATLAS-104 generates it; the renderer's D2
seam). Templates are selected by explicit ``version=`` — ATLAS-104's job;
this ticket just makes them selectable.
"""

import hashlib
from collections.abc import Callable
from pathlib import Path

import pytest

from atlas.planning import (
    MissingVariableError,
    SourceDocument,
    UndeclaredVariableError,
    current_release,
    render_planner_prompt,
)
from atlas.planning.renderer import CurrentReleaseError

FIXTURE_SCHEMA = (
    '{"$comment": "FIXTURE per-stage projection schema - generated by ATLAS-104"}'
)

VariablesFactory = Callable[[], dict[str, object]]

EPICS_VERSION = "planner-stage-epics-v1.0.0"
EPICS_V1_1_0_VERSION = "planner-stage-epics-v1.1.0"
TICKETS_VERSION = "planner-stage-tickets-v1.0.0"
TICKETS_V1_1_0_VERSION = "planner-stage-tickets-v1.1.0"
TICKETS_V1_2_0_VERSION = "planner-stage-tickets-v1.2.0"
TICKETS_V1_3_0_VERSION = "planner-stage-tickets-v1.3.0"
TICKETS_V1_4_0_VERSION = "planner-stage-tickets-v1.4.0"
DEPENDENCIES_VERSION = "planner-stage-dependencies-v1.0.0"

# A retained prior single-call template (no longer the live release since
# ATLAS-111 bumped CURRENT to planner-v1.2.0): pin its file bytes so the
# retained artifact is never edited in place — historical PlanRuns reproduce.
SINGLE_CALL_VERSION = "planner-v1.1.0"
SINGLE_CALL_FILE_SHA256 = (
    "8e4e4a4aaf9a547595954524aede0db8f45f7cf1ebd99a825c5c53141369208f"
)

DOCUMENTS = [
    SourceDocument(path="docs/a.md", sha="sha-aaa", content="# A\n"),
    SourceDocument(path="docs/b.md", sha="sha-bbb", content="# B\n"),
]

# The valid-anchor list payload (ATLAS-111): {anchor, heading} dicts, as the
# pipeline derives from AnchorIndex.anchor_choices().
VALID_ANCHORS = [
    {"anchor": "docs/a.md#a", "heading": "A"},
    {"anchor": "docs/b.md#b", "heading": "B"},
]


def epics_variables() -> dict[str, object]:
    return {
        "product_key": "ATLAS",
        "documents": DOCUMENTS,
        "stage_output_schema": FIXTURE_SCHEMA,
    }


def tickets_variables() -> dict[str, object]:
    return {
        "product_key": "ATLAS",
        "documents": DOCUMENTS,
        "epic": {
            "title": "Planning Engine",
            "objective": "Generate a backlog",
            "description": "The plan/apply loop",
        },
        "epic_index": "new_epic:0",
        "assembled_epics": [
            {"index": "new_epic:0", "title": "Planning Engine"},
            {"index": "new_epic:1", "title": "Dependency Engine"},
        ],
        "stage_output_schema": FIXTURE_SCHEMA,
    }


def dependencies_variables() -> dict[str, object]:
    return {
        "product_key": "ATLAS",
        "documents": DOCUMENTS,
        "assembled_tickets": [
            {"index": "new:0", "title": "Document ingestion", "epic_ref": "new_epic:0"},
            {"index": "new:1", "title": "Reconciler", "epic_ref": "new_epic:0"},
        ],
        "stage_output_schema": FIXTURE_SCHEMA,
    }


STAGES = (
    pytest.param(EPICS_VERSION, epics_variables, id="epics"),
    pytest.param(TICKETS_VERSION, tickets_variables, id="tickets"),
    pytest.param(DEPENDENCIES_VERSION, dependencies_variables, id="dependencies"),
)


# --- each staged template renders deterministically with a stable hash -------


@pytest.mark.parametrize("version, variables", STAGES)
def test_staged_template_renders_deterministically(
    version: str, variables: VariablesFactory
) -> None:
    first = render_planner_prompt(variables(), version=version)
    second = render_planner_prompt(variables(), version=version)
    assert first.text == second.text
    assert first.prompt_version == version


@pytest.mark.parametrize("version, variables", STAGES)
def test_staged_prompt_hash_is_sha256_of_text(
    version: str, variables: VariablesFactory
) -> None:
    rendered = render_planner_prompt(variables(), version=version)
    expected = hashlib.sha256(rendered.text.encode("utf-8")).hexdigest()
    assert rendered.prompt_hash == expected


@pytest.mark.parametrize("version, variables", STAGES)
def test_staged_template_embeds_caller_supplied_schema(
    version: str, variables: VariablesFactory
) -> None:
    text = render_planner_prompt(variables(), version=version).text
    assert FIXTURE_SCHEMA in text


# --- variable validation: fail closed in both directions ---------------------


@pytest.mark.parametrize("version, variables", STAGES)
def test_each_missing_declared_variable_fails_before_render(
    version: str, variables: VariablesFactory
) -> None:
    for name in list(variables()):
        broken = variables()
        del broken[name]
        with pytest.raises(MissingVariableError, match=name):
            render_planner_prompt(broken, version=version)


@pytest.mark.parametrize("version, variables", STAGES)
def test_undeclared_extra_variable_fails(
    version: str, variables: VariablesFactory
) -> None:
    with pytest.raises(UndeclaredVariableError, match="surprise"):
        render_planner_prompt(variables() | {"surprise": 1}, version=version)


