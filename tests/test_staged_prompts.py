@pytest.mark.parametrize(
    "version", [EPICS_VERSION, TICKETS_VERSION, DEPENDENCIES_VERSION]
)
def test_staged_names_cannot_repoint_current(tmp_path: Path, version: str) -> None:
    # A can't-repoint invariant, not a didn't-repoint check: the renderer's
    # CURRENT _VERSION_RE structurally rejects staged names, so the staged
    # set can never become the live release by editing CURRENT.
    directory = tmp_path / "prompts"
    directory.mkdir()
    (directory / "CURRENT").write_text(f"{version}\n", encoding="utf-8")
    with pytest.raises(CurrentReleaseError, match=version):
        render_planner_prompt({}, prompts_dir=directory)
